/* =========================================================
   NAVIGATION
   ========================================================= */

function initNavigation() {
  const sections = [
    "birthday",
    "memories",
    "quiz",
    "game",
    "letters",
    "surprise",
    "finale"
  ];

  $$(".story-dot").forEach(
    (dot) => {
      dot.addEventListener(
        "click",
        () => {
          document
            .getElementById(
              dot.dataset.target
            )
            .scrollIntoView({
              behavior: "smooth"
            });
        }
      );
    }
  );

  const observer =
    new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (!entry.isIntersecting)
            return;

          const index =
            sections.indexOf(
              entry.target.id
            );

          $$(".story-dot").forEach(
            (dot, i) => {
              dot.classList.toggle(
                "active",
                i === index
              );
            }
          );
        });
      },
      {
        threshold: 0.35
      }
    );

  sections.forEach((id) => {
    const el =
      document.getElementById(id);

    if (el) {
      observer.observe(el);
    }
  });
}


