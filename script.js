let quizIndex = 0;
let quizScore = 0;

function initQuiz() {
  renderQuiz();

  $("#nextQuestion").addEventListener(
    "click",
    () => {
      quizIndex++;

      if (
        quizIndex >=
        birthdayConfig.quizQuestions.length
      ) {
        return showQuizResult();
      }

      renderQuiz();
    }
  );
}

function renderQuiz() {
  const q =
    birthdayConfig.quizQuestions[quizIndex];

  $("#quizCount").textContent =
    `Question ${quizIndex + 1} / ${birthdayConfig.quizQuestions.length}`;

  $("#quizScore").textContent =
    `Score ${quizScore}`;

  $("#quizProgress").style.width =
    `${(quizIndex / birthdayConfig.quizQuestions.length) * 100}%`;

  $("#quizQuestion").textContent =
    q.question;

  $("#quizFeedback").textContent = "";

  $("#nextQuestion").classList.add("hidden");

  const box = $("#quizOptions");

  box.innerHTML = "";

  q.options.forEach((opt, i) => {
    const button =
      document.createElement("button");

    button.className = "quiz-option";
    button.textContent = opt;

    button.addEventListener(
      "click",
      () => answerQuiz(i)
    );

    box.appendChild(button);
  });
}

function answerQuiz(choice) {
  const q =
    birthdayConfig.quizQuestions[quizIndex];

  const buttons =
    $$(".quiz-option");

  buttons.forEach(
    (button) => {
      button.disabled = true;
    }
  );

  buttons[q.answer].classList.add(
    "correct"
  );

  if (choice === q.answer) {
    quizScore++;

    $("#quizFeedback").textContent =
      q.correct;

    launchConfetti(7);
  } else {
    buttons[choice].classList.add(
      "wrong"
    );

    $("#quizFeedback").textContent =
      q.wrong;
  }

  $("#quizScore").textContent =
    `Score ${quizScore}`;

  $("#nextQuestion").textContent =
    quizIndex ===
    birthdayConfig.quizQuestions.length - 1
      ? "SEE MY RESULT →"
      : "NEXT →";

  $("#nextQuestion").classList.remove(
    "hidden"
  );
}

function showQuizResult() {
  const total =
    birthdayConfig.quizQuestions.length;

  const pct =
    (quizScore / total) * 100;

  let msg =
    pct >= 90
      ? "Okay, okay... you officially know us too well. 👀❤️"
      : pct >= 70
      ? "Not bad. 3 years haven't gone to waste 😂"
      : "We need to have a serious friendship meeting. 😭";

  $("#quizProgress").style.width =
    "100%";

  $("#quizQuestion").innerHTML = `
    <div class="quiz-result">
      <strong>${quizScore}/${total}</strong>
      ${msg}
    </div>
  `;

  $("#quizOptions").innerHTML = "";

  $("#quizFeedback").textContent = "";

  $("#nextQuestion").classList.add(
    "hidden"
  );
}


