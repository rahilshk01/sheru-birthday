function startGame() {
  if (gameRunning) return;

  gameRunning = true;
  gameScore = 0;

  $("#gameScore").textContent = "0";
  $("#gameTime").textContent = "30";
  $("#gameResult").textContent = "";

  $("#gameBoard").innerHTML = "";

  $("#startGame").textContent = "GO! ♥";

  spawnHeart();

  let time = 30;

  gameTimer = setInterval(() => {
    time--;

    $("#gameTime").textContent = time;

    if (time <= 0) {
      endGame();
    }
  }, 1000);
}

function spawnHeart() {
  if (!gameRunning) return;

  const h =
    document.createElement("button");

  h.className = "heart";
  h.type = "button";
  h.textContent = "♥";

  h.setAttribute(
    "aria-label",
    "Catch heart"
  );

  h.style.left =
    `${Math.random() * 88 + 4}%`;

  h.style.top =
    `${Math.random() * 75 + 15}%`;

  h.style.fontSize =
    `${1.2 + Math.random() * 1.3}rem`;

  h.addEventListener(
    "click",
    () => {
      gameScore++;

      $("#gameScore").textContent =
        gameScore;

      h.remove();

      launchConfetti(1);

      spawnHeart();
    },
    { once: true }
  );

  $("#gameBoard").appendChild(h);

  setTimeout(() => {
    h.remove();
  }, 2300);

  setTimeout(
    spawnHeart,
    Math.random() * 500 + 350
  );
}

function endGame() {
  gameRunning = false;

  clearInterval(gameTimer);

  $$(".heart").forEach(
    (heart) => heart.remove()
  );

  $("#startGame").textContent =
    "PLAY AGAIN ♥";

  const msg =
    gameScore <= 5
      ? "Sheru... were you even trying? 😭"
      : gameScore <= 15
      ? "Okay okay, not bad 😂❤️"
      : gameScore <= 25
      ? "Certified heart collector 🫶🏻"
      : "Fine. You win. 👑❤️";

  $("#gameResult").textContent =
    `${gameScore} hearts — ${msg}`;
}


