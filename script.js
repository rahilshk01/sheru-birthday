/* =========================================================
   CONFETTI
   ========================================================= */

function launchConfetti(count = 12) {
  const reduced =
    window.matchMedia(
      "(prefers-reduced-motion: reduce)"
    ).matches;

  if (reduced) return;

  for (let i = 0; i < count; i++) {
    const s =
      document.createElement("span");

    s.textContent =
      Math.random() > 0.5
        ? "♥"
        : "✦";

    s.style.cssText = `
      position: fixed;
      z-index: 60;
      left: ${45 + Math.random() * 10}%;
      top: ${42 + Math.random() * 8}%;
      color: ${
        Math.random() > 0.3
          ? "#ff8fb3"
          : "#fff"
      };
      pointer-events: none;
      font-size: ${
        10 + Math.random() * 12
      }px;
    `;

    document.body.appendChild(s);

    const x =
      (Math.random() - 0.5) * 260;

    const y =
      -(80 + Math.random() * 260);

    s.animate(
      [
        {
          transform:
            "translate(0,0) scale(.5)",
          opacity: 0
        },
        {
          transform:
            `translate(${x * 0.35}px,${y * 0.35}px) scale(1)`,
          opacity: 1
        },
        {
          transform:
            `translate(${x}px,${y}px) scale(.4)`,
          opacity: 0
        }
      ],
      {
        duration:
          900 + Math.random() * 600,
        easing:
          "cubic-bezier(.2,.7,.3,1)"
      }
    )
      .finished
      .then(() => s.remove())
      .catch(() => s.remove());
  }
}